import {
	FIXED_FACES,
	FONT_PAIRS,
	FONT_ROLES,
} from "../../src/design/font-pairs";
import { TYPE } from "../../src/design/type";

const UPPER = /[A-Z]/g;

export const kebab = (name: string) =>
	name.replace(UPPER, (c) => `-${c.toLowerCase()}`);

const px = (n: number) => `${n}px`;

/**
 * src/themes/type.generated.css: the font role defaults, the fixed faces and
 * one `type-<variant>` utility per entry in TYPE.
 *
 * Tailwind needs the role variables in `@theme` to make `font-<role>` classes;
 * the values here are Default's, and every theme variant sets its own
 * (themes.generated.css).
 */
export function renderTypeCss(): string {
	const roleDefaults = FONT_ROLES.map(
		(r) => `\t--font-${r}: "${FONT_PAIRS.warm[r]}";`
	);
	const fixed = Object.entries(FIXED_FACES).map(
		([k, v]) => `\t--font-${k}: "${v}";`
	);
	const utilities = Object.entries(TYPE).map(([name, s]) => {
		const decls = [
			`font-family: var(--font-${s.font});`,
			`font-size: ${px(s.fontSize)};`,
			`line-height: ${px(s.lineHeight)};`,
			...("letterSpacing" in s
				? [`letter-spacing: ${px(s.letterSpacing)};`]
				: []),
		];
		return `@utility type-${kebab(name)} {\n${decls.map((d) => `\t${d}`).join("\n")}\n}`;
	});
	return `/* Generated by scripts/gen-themes.ts from src/design/font-pairs.ts and src/design/type.ts. Don't edit; run \`bun run themes\`. */
@theme {
${roleDefaults.join("\n")}
}

/* Faces that don't follow the theme. */
@theme static {
${fixed.join("\n")}
}

${utilities.join("\n\n")}
`;
}

/** src/design/type-classes.generated.ts: the `type-*` class names as literals, so Tailwind finds them. */
export function renderTypeClasses(): string {
	const entries = Object.keys(TYPE)
		.map((name) => `\t${name}: "type-${kebab(name)}",`)
		.join("\n");
	return `// Generated by scripts/gen-themes.ts. Don't edit; run \`bun run themes\`.
import type { TypeVariant } from "./type";

export const TYPE_CLASS: Record<TypeVariant, string> = {
${entries}
};
`;
}

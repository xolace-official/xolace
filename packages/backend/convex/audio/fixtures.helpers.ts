type Encoding = { bits: number; float?: boolean; extensible?: boolean };

/** A WAV file (8 kHz) holding `frames` (each a sample per channel, −1 to 1). */
export function makeWav(
	frames: readonly (readonly number[])[],
	{ bits, float = false, extensible = false }: Encoding = { bits: 16 },
	{
		before = [] as Uint8Array[],
		dataSize,
	}: { before?: Uint8Array[]; dataSize?: number } = {}
) {
	const channels = frames[0]?.length ?? 1;
	const width = bits / 8;
	const data = new Uint8Array(frames.length * channels * width);
	const view = new DataView(data.buffer);
	frames.forEach((frame, f) => {
		frame.forEach((x, c) => {
			const at = (f * channels + c) * width;
			if (float) {
				view.setFloat32(at, x, true);
			} else if (bits === 8) {
				view.setUint8(at, Math.round(x * 127) + 128);
			} else if (bits === 16) {
				view.setInt16(at, Math.round(x * 0x7f_ff), true);
			} else if (bits === 24) {
				const v = Math.round(x * 0x7f_ff_ff);
				view.setUint16(at, v & 0xff_ff, true);
				view.setInt8(at + 2, v >> 16);
			} else {
				view.setInt32(at, Math.round(x * 0x7f_ff_ff_ff), true);
			}
		});
	});
	const fmt = new Uint8Array(extensible ? 40 : 16);
	const f = new DataView(fmt.buffer);
	const tag = float ? 3 : 1;
	f.setUint16(0, extensible ? 0xff_fe : tag, true);
	f.setUint16(2, channels, true);
	f.setUint32(4, 8000, true);
	f.setUint32(8, 8000 * channels * width, true);
	f.setUint16(12, channels * width, true);
	f.setUint16(14, bits, true);
	if (extensible) {
		f.setUint16(16, 22, true);
		f.setUint16(24, tag, true);
	}
	const chunk = (id: string, body: Uint8Array, size = body.length) => {
		const head = new Uint8Array(8);
		head.set([...id].map((ch) => ch.charCodeAt(0)));
		new DataView(head.buffer).setUint32(4, size, true);
		const pad = body.length % 2 ? new Uint8Array(1) : new Uint8Array(0);
		return [head, body, pad];
	};
	const parts = [
		...chunk("fmt ", fmt),
		...before,
		...chunk("data", data, dataSize),
	];
	const body = new Uint8Array(4 + parts.reduce((n, p) => n + p.length, 0));
	body.set([..."WAVE"].map((ch) => ch.charCodeAt(0)));
	let at = 4;
	for (const p of parts) {
		body.set(p, at);
		at += p.length;
	}
	const riff = new Uint8Array(8 + body.length);
	riff.set([..."RIFF"].map((ch) => ch.charCodeAt(0)));
	new DataView(riff.buffer).setUint32(4, body.length, true);
	riff.set(body, 8);
	return riff;
}

